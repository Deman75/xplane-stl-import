/* Build the offline assets script. The browser cannot fetch local file:// data. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const templateName='PlaneMaker12_template.acf';
const airfoils=fs.readdirSync(path.join(root,'Airfoils')).filter(n=>/\.afl$/i.test(n)).sort()
  .map(name=>({name,text:fs.readFileSync(path.join(root,'Airfoils',name),'utf8')}));
const template={name:templateName,text:fs.readFileSync(path.join(root,'input',templateName),'utf8')};
const P=require('../web/plane.js');
P.validateTemplate(template.text);for(const f of airfoils)P.parseAFL(f.text,f.name);
fs.writeFileSync(path.join(root,'web/bundled-assets.js'),
  '/* Generated by tools/build-bundle.cjs; edit Airfoils/ and input/ instead. */\n'+
  'globalThis.BundledAircraftAssets='+JSON.stringify({airfoils,template})+';\n');
console.log('Bundled '+airfoils.length+' AFL files and '+templateName);
